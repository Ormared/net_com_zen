"""Generate and run the centralized ROS 2 RMW benchmark matrix.

The generator writes explicit, reviewable YAML.  Runs remain serial because
timing benchmarks must not contend with one another::

    python -m netcom_zen.harness.centralized_lab generate
    sudo .pixi/envs/ros2/bin/python -m netcom_zen.harness.sweep \
      scenarios/centralized/single_n32_sweep.yaml -o results/centralized/single_n32
"""
from __future__ import annotations

